// 文件名：gmp_story.go
package main

import (
	"fmt"
	"runtime"
	"sync"
	"sync/atomic"
	"time"
)

func main() {
	// =====================================================================
	// 🎬 第一幕：GMP 模型概述 & M、P、G 的关系
	// =====================================================================
	fmt.Println("=== 第一幕：工厂的基本架构 ===")
	// P 的数量（工位数量）。默认等于 CPU 核心数。
	// 工厂有多大，取决于你租了几个工位（GOMAXPROCS）。如果只有 1 个工位，就算雇 1000 个工人，也只能排队一次进一个人。
	fmt.Printf("【工厂配置】当前 CPU 核心数（默认工位 P 数量）: %d\n", runtime.NumCPU())
	
	// 演示 G 的关系：G 就是任务。
	// 如果我们直接执行一个函数，它跑在 M（主线程）绑定的 P（主工位）上。
	// 如果加了 `go` 关键字，它就成了独立的小砖头（G），被扔进队列。
	var wg sync.WaitGroup
	wg.Add(1)
	go func() {
		defer wg.Done()
		fmt.Println("【大厂日常】我是一个 G（小任务），我正在某个 P（工位）上，被 M（工人）搬运着。")
	}()
	wg.Wait()

	// =====================================================================
	// 🎬 第二幕：Goroutine 调度原理 & 工作窃取（Work Stealing）
	// =====================================================================
	fmt.Println("\n=== 第二幕：工作窃取机制（防止有人闲死，有人忙死）===")
	// 假设有 4 个工位（P），每个工位的小车（本地队列）最多放 256 个 G。
	// 我们启动了 10 个 G，它们会平均分配到不同的 P 的队列里。
	// 如果一个 P 的队列空了，它不会闲着，它会去其他 P 的队列里“偷”一半的任务过来。
	
	// 强制把 P 设置为 4，方便观察
	runtime.GOMAXPROCS(4) 
	
	var taskWg sync.WaitGroup
	// 启动 12 个任务，看它们如何被分配到不同的 M 和 P 上
	for i := 1; i <= 12; i++ {
		taskWg.Add(1)
		go func(taskID int) {
			defer taskWg.Done()
			// 模拟干活（睡眠几十毫秒）
			time.Sleep(50 * time.Millisecond)
			fmt.Printf("  [任务 %d] 完成！\n", taskID)
		}(i)
	}
	taskWg.Wait()
	fmt.Println("-> 注意看，虽然任务很多，但它们被 4 个工位完美瓜分了，没有出现一直阻塞的情况。")

	// =====================================================================
	// 🎬 第三幕：调度器工作流程（本地队列 -> 全局队列 -> 工作窃取）
	// =====================================================================
	fmt.Println("\n=== 第三幕：调度器找活干的顺序 ===")
	// 一个 M（工人）找不到 G（任务）时，按顺序找：
	// 1. 看自己 P 的本地队列（查小车）
	// 2. 看全局队列（去厂长办公室拿单子，需要加锁）
	// 3. 看其他 P 的本地队列（去偷别人的单子）
	// 代码层面很难直接演示调度顺序，但我们可以看运行时的状态：
	
	var beforeGoroutines = runtime.NumGoroutine()
	fmt.Printf("当前 G 数量（包含 main）: %d\n", beforeGoroutines)

	// =====================================================================
	// 🎬 第四幕：抢占式调度（拯救被“死循环”霸占的工位）
	// =====================================================================
	fmt.Println("\n=== 第四幕：抢占式调度（Go 1.14 之后的超能力）===")
	// 设想：一个工人（M）搬运了一个 G，这个 G 里写了个死循环（纯计算，没有系统调用，也不 sleep）。
	// 在 Go 1.14 之前，这个工人会一直卡在这个死循环里，导致其他工位的人分不到活干，整个工厂停摆。
	// 现在有了【抢占式调度】，操作系统会定期给这个工人发信号，强行让他把手里的活放下，让给别人干。
	
	var isDone int32 = 0 // 用原子操作标记任务完成
	
	// 启动一个死循环 G，试图霸占一个 M
	go func() {
		for {
			// 如果任务已经被主程序标记完成，就退出死循环
			if atomic.LoadInt32(&isDone) == 1 {
				return
			}
			// 纯计算，死死霸占 CPU
		}
	}()

	// 主程序故意 sleep 100 毫秒，让上面的死循环开始跑
	time.Sleep(100 * time.Millisecond)
	
	// 如果是在 Go 1.14 之前，上面的死循环如果不结束，下面的代码可能会一直等不到 CPU。
	// 但现在，主程序可以轻松抢到 CPU 并执行到这里：
	fmt.Println("-> 主程序：我来测试一下，我还能正常执行吗？能！说明死循环没有把我们卡死！")
	
	atomic.StoreInt32(&isDone, 1) // 通知死循环结束
	time.Sleep(50 * time.Millisecond)

	// =====================================================================
	// 🎬 第五幕：G 的轻量级（内存开销极小）
	// =====================================================================
	fmt.Println("\n=== 第五幕：十万大军的降维打击（轻量级验证）===")
	
	var mem runtime.MemStats
	runtime.ReadMemStats(&mem)
	beforeMem := mem.Alloc

	var massWg sync.WaitGroup
	// 开启 100000 个 G
	for i := 0; i < 100000; i++ {
		massWg.Add(1)
		go func() {
			defer massWg.Done()
			time.Sleep(10 * time.Millisecond) // 稍微干点活
		}()
	}
	
	massWg.Wait()
	runtime.ReadMemStats(&mem)
	afterMem := mem.Alloc
	
	fmt.Printf("10 万个 G 跑完，仅消耗了 %d KB 的堆内存！\n", (afterMem-beforeMem)/1024)
	fmt.Println("-> 相当于每个 G 只花了不到 2KB 的内存！如果用操作系统的线程（每个约 1MB-8MB），100000 个线程会让 100GB 内存瞬间爆炸！")

	// =====================================================================
	// 🎬 第六幕：性能优化建议
	// =====================================================================
	fmt.Println("\n=== 第六幕：工厂厂长（性能调优）的保命守则 ===")
	fmt.Println("1. 别瞎改 P 的数量：除非你知道你的机器是几核，且业务极端依赖 CPU，否则别动 runtime.GOMAXPROCS，它默认就是最优解。")
	fmt.Println("2. 防止 G 泄漏：一定要确保启动的 G 有退出机制（比如监听 ctx.Done()），否则千万个 G 永远挂在内存里，撑爆你的服务器。")
	fmt.Println("3. 大量 IO 用 Network Poller：如果一个 G 去读普通文件（阻塞系统调用），M（工人）会被操作系统挂起，导致工人不够用。如果用网络 IO（如 HTTP 请求），Go 会在底层用 Epoll 异步处理，绝不浪费工人。")
	
	fmt.Println("\n🎉 全部演示结束！")
}
// ============================================================================
// 🧩 第一题：有效的括号 (Valid Parentheses)
// ============================================================================
// 思路：利用“栈”后进先出（LIFO）的特性。
// 遇到左括号就压入栈中；遇到右括号，就去看看栈顶是不是和它匹配的左括号。
// 匹配就把栈顶弹出去，不匹配说明顺序乱了，直接返回 false。
// 最后如果栈空了，说明全都完美配对。

func isValid(s string) bool {
	// 【防坑 1】：如果字符串长度是奇数，绝对不可能成对，直接 false
	if len(s)%2 != 0 {
		return false
	}

	// 建立一个对照表（Hash Map）：右括号 -> 左括号
	// 这样查起来非常快，不用写一大堆 if else
	pairs := map[byte]byte{
		')': '(',
		']': '[',
		'}': '{',
	}

	// 用切片模拟一个栈（水池）
	// 栈顶就是切片的最后一个元素：stack[len(stack)-1]
	stack := []byte{}

	// 遍历字符串里的每一个字符
	for i := 0; i < len(s); i++ {
		char := s[i] // 获取当前字符

		// 去对照表里查一下，当前字符是不是“右括号”
		// 如果查到了，ok 就是 true；没查到，说明是“左括号”
		if left, ok := pairs[char]; ok {
			// 【防坑 2】：如果栈是空的（比如第一个字符就是 ')'），或者栈顶的左括号和当前右括号不匹配
			if len(stack) == 0 || stack[len(stack)-1] != left {
				return false
			}
			// 匹配成功：把栈顶的左括号弹出去（即切片砍掉最后一个元素）
			stack = stack[:len(stack)-1]
		} else {
			// 如果是左括号，直接压入栈中（切片追加元素）
			stack = append(stack, char)
		}
	}

	// 【防坑 3】：遍历结束后，如果栈里还有剩余的左括号（比如只输入了一个 "("），也是无效的
	return len(stack) == 0
}

// 测试有效的括号
func testBrackets() {
	// LeetCode 官方提供的测试用例
	testCases := []string{
		"()",       // 预期：true
		"()[]{}",   // 预期：true
		"(]",       // 预期：false
		"([])",     // 预期：true
		"([)]",     // 预期：false（经典交叉错误）
	}

	for _, s := range testCases {
		result := isValid(s)
		fmt.Printf("输入: \"%-6s\" -> 输出: %v\n", s, result)
	}
}

// ============================================================================
// 🧩 第二题：最长公共前缀 (Longest Common Prefix)
// ============================================================================
// 思路：纵向扫描法（一列一列地比较）。
// 拿第一个字符串当“基准”，依次看它的第 0 个字符、第 1 个字符...
// 每次拿出一个字符，去和数组中所有其他字符串对应的位置做比较。
// 一旦发现越界，或者字符不一致，说明最长前缀到此为止，直接截取前面匹配的部分返回。

func longestCommonPrefix(strs []string) string {
	// 【防坑 1】：如果传进来的是空数组，直接返回空字符串
	if len(strs) == 0 {
		return ""
	}

	// 以第一个字符串为基准，逐个字符开始扫描
	// i 代表当前比较的是第几个字符
	for i := 0; i < len(strs[0]); i++ {
		// 获取基准字符串在当前列的字符
		char := strs[0][i]

		// 拿这个字符，去和后面的每一个字符串（从索引 1 开始）比对
		for j := 1; j < len(strs); j++ {
			// 【防坑 2】：极其容易越界！
			// 如果 i 已经大于或等于某个字符串的长度，说明这个字符串比较短，已经到头了
			// 或者该位置的字符和基准字符不一致
			if i >= len(strs[j]) || strs[j][i] != char {
				// 返回第一个字符串的前 i 个字符（注意：[0:i] 表示从 0 开始，到 i 之前，不包含 i）
				return strs[0][:i]
			}
		}
	}

	// 如果循环完整跑完了，说明第一个字符串就是最短的，它本身就是最长公共前缀
	return strs[0]
}

// 测试最长公共前缀
func testPrefix() {
	// LeetCode 官方提供的测试用例
	testCases := [][]string{
		{"flower", "flow", "flight"}, // 预期："fl"
		{"dog", "racecar", "car"},    // 预期：""（因为第一个字符就不同）
		{"a"},                        // 预期："a"
		{"ab", "a"},                  // 预期："a"（防越界测试）
	}

	for _, strs := range testCases {
		result := longestCommonPrefix(strs)
		// 注意：这里用 %v 格式化数组，用 %q 格式化字符串（带有双引号）
		fmt.Printf("输入: %-28v -> 输出: %q\n", strs, result)
	}
}